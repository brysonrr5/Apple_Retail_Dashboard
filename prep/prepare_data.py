"""Clean the Apple sales workbook and write data/data.js, the file the dashboard loads.

Run from the dashboard folder (needs Python 3 with pandas and openpyxl; takes about a minute):
    python3 prep/prepare_data.py path/to/Apple_Sales_Data_3331_Version2.xlsx
"""
import pandas as pd, json, sys, os
HERE=os.path.dirname(os.path.abspath(__file__))
OUT=os.path.join(HERE,'..','data','data.js')
sheets=pd.read_excel(sys.argv[1], sheet_name=None, engine='openpyxl')
cat=sheets['Category']; prod=sheets['Products']; stores=sheets['Stores']; sales=sheets['Sales']; war=sheets['Warranty']
log={}
log['raw_sales_rows']=len(sales); log['raw_claims']=len(war)

# 1. Exclude the incomplete final month (data stops 12 Nov 2024)
cut=pd.Timestamp('2024-11-01')
dropped=sales[sales.sale_date>=cut]
log['dropped_nov2024_rows']=len(dropped); log['last_sale_date']=str(sales.sale_date.max().date())
sales=sales[sales.sale_date<cut].copy()
war=war[war.sale_id.isin(sales.sale_id)].copy()
log['claims_dropped_with_those_sales']=log['raw_claims']-len(war)

# 2. Join lookups, derive revenue = quantity x list price
s=(sales.merge(prod,left_on='product_id',right_on='Product_ID',how='left',validate='m:1')
        .merge(cat,left_on='Category_ID',right_on='category_id',how='left',validate='m:1')
        .merge(stores,left_on='store_id',right_on='Store_ID',how='left',validate='m:1'))
assert s[['Product_Name','category_name','Store_Name']].notna().all().all()
s['revenue']=s.quantity*s.Price
s['mi']=(s.sale_date.dt.year-2020)*12+s.sale_date.dt.month-1
s['year']=s.sale_date.dt.year
log['sales_before_launch_rows']=int((s.sale_date<s.Launch_Date).sum())

# 3. Unique display labels (6 store names and 1 product name are reused under different IDs)
dup_st=stores.Store_Name[stores.Store_Name.duplicated(keep=False)]
stores['label']=[f"{n} ({i})" if n in set(dup_st) else n for n,i in zip(stores.Store_Name,stores.Store_ID)]
pc=prod.merge(cat,left_on='Category_ID',right_on='category_id')
dup_p=set(pc.Product_Name[pc.Product_Name.duplicated(keep=False)])
pc['label']=[f"{n} ({c})" if n in dup_p else n for n,c in zip(pc.Product_Name,pc.category_name)]
log['duplicate_store_names']=sorted(set(dup_st)); log['duplicate_product_names']=sorted(dup_p)

# 4. Warranty: attach each claim to its sale
w=war.merge(s[['sale_id','mi','store_id','Category_ID','sale_date']],on='sale_id',how='left',validate='1:1')
log['claims_before_sale_date']=int((w.claim_date<w.sale_date).sum())
log['claim_date_range']=[str(w.claim_date.min().date()),str(w.claim_date.max().date())]
statuses=['Completed','In Progress','Pending','Rejected']

# Index lookups
cat_list=cat.category_name.tolist(); cat_idx={c:i for i,c in enumerate(cat.category_id)}
countries=sorted(stores.Country.unique()); country_idx={c:i for i,c in enumerate(countries)}
store_idx={sid:i for i,sid in enumerate(stores.Store_ID)}
prod_idx={pid:i for i,pid in enumerate(pc.Product_ID)}

# Cube A: month x store x category
a=s.groupby(['mi','store_id','Category_ID']).agg(units=('quantity','sum'),rev=('revenue','sum'),n=('sale_id','size')).reset_index()
wc=w.groupby(['mi','store_id','Category_ID','repair_status']).size().unstack(fill_value=0).reindex(columns=statuses,fill_value=0).reset_index()
a=a.merge(wc,on=['mi','store_id','Category_ID'],how='left').fillna(0)
cubeA=[[int(r['mi']),store_idx[r['store_id']],cat_idx[r['Category_ID']],int(r['units']),int(r['rev']),int(r['n'])]+[int(r[c]) for c in statuses] for r in a.to_dict('records')]

# Cube B: year x country x product (for product rankings)
b=s.groupby(['year','Country','product_id']).agg(units=('quantity','sum'),rev=('revenue','sum'),n=('sale_id','size')).reset_index()
cubeB=[[int(r.year)-2020,country_idx[r.Country],prod_idx[r.product_id],int(r.units),int(r.rev),int(r.n)] for r in b.itertuples(index=False)]

data={
 'meta':{'firstMonth':'2020-01','months':int(s.mi.max())+1,'statuses':statuses,
         'note':'Sales 1 Jan 2020 - 31 Oct 2024. Nov 2024 excluded (incomplete).'},
 'categories':cat_list,'countries':countries,
 'stores':[[l,country_idx[c],city] for l,c,city in zip(stores.label,stores.Country,stores.City)],
 'products':[[l,cat_idx[c]] for l,c in zip(pc.label,pc.Category_ID)],
 'cubeA':cubeA,'cubeB':cubeB}
js='// Generated by prep.py from Apple_Sales_Data_3331_Version2.xlsx. Do not edit by hand.\n'
js+='// cubeA rows: [monthIndex, storeIndex, categoryIndex, units, revenue, sales, claimsCompleted, claimsInProgress, claimsPending, claimsRejected]\n'
js+='// cubeB rows: [yearIndex, countryIndex, productIndex, units, revenue, sales]\n'
js+='const DASHBOARD_DATA = '+json.dumps(data,separators=(',',':'))+';\n'
open(OUT,'w').write(js)
log.update(clean_sales_rows=len(s),clean_claims=len(w),cubeA_rows=len(cubeA),cubeB_rows=len(cubeB),datajs_bytes=len(js))
print('Cleaning summary:'); print(json.dumps(log,indent=1))
